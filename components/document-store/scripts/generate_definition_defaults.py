"""Generate document_store/services/_definition_defaults.py from the models.

The merge restore compares an archive's definitions (terminologies, terms,
templates) with the target's as raw Mongo rows. A row written before a
field existed lacks the key, and the model reads it as the field's default;
the comparison must too. Document-store cannot import def-store or
template-store at runtime (separate services), so their defaults are
generated into a module here, and a contract test regenerates them and fails
when the module falls behind the models.

Run from the repository root:

    PYTHONPATH=components/def-store/src:components/template-store/src:libs/wip-auth/src \\
        .venv/bin/python components/document-store/scripts/generate_definition_defaults.py

Pass --check to compare instead of write (exit 1 on a difference).
"""

from __future__ import annotations

import datetime
import enum
import pprint
import sys
import typing
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic_core import PydanticUndefined

OUT = (
    Path(__file__).resolve().parents[1]
    / "src" / "document_store" / "services" / "_definition_defaults.py"
)

# Storage bookkeeping, never compared (the merge excludes audit and id fields).
_SKIP_FIELDS = frozenset({"id", "revision_id"})


def _roots() -> dict[str, type[BaseModel]]:
    from def_store.models.term import Term
    from def_store.models.terminology import Terminology
    from template_store.models.template import Template

    return {"terminologies": Terminology, "terms": Term, "templates": Template}


def _nested_model(annotation: Any) -> tuple[type[BaseModel], bool] | None:
    """(model, many) when the field holds a model or a list of models."""
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation, False
    if origin in (list, tuple) and args:
        inner = _nested_model(args[0])
        return (inner[0], True) if inner else None
    for arg in args:  # Optional[...] / unions
        if arg is type(None):
            continue
        found = _nested_model(arg)
        if found:
            return found
    return None


def _as_stored(value: Any) -> Any:
    """A default as a Mongo row holds it (enums by value, models as dicts)."""
    if isinstance(value, BaseModel):
        return value.model_dump(mode="json")
    if isinstance(value, enum.Enum):
        return value.value
    if isinstance(value, list):
        return [_as_stored(v) for v in value]
    if isinstance(value, dict):
        return {k: _as_stored(v) for k, v in value.items()}
    return value


def build() -> dict[str, Any]:
    models: dict[str, dict[str, Any]] = {}

    def visit(model: type[BaseModel]) -> str:
        name = model.__name__
        if name in models:
            return name
        spec: dict[str, Any] = {"defaults": {}, "nested": {}}
        models[name] = spec
        for field_name, info in model.model_fields.items():
            if field_name in _SKIP_FIELDS:
                continue
            nested = _nested_model(info.annotation)
            if nested:
                spec["nested"][field_name] = [visit(nested[0]), nested[1]]
            if info.default is not PydanticUndefined:
                default = info.default
            elif info.default_factory is not None:
                default = info.default_factory()  # type: ignore[call-arg]
            else:
                continue  # required: no default to fill
            if isinstance(default, datetime.datetime):
                continue  # timestamps are audit fields, never compared
            spec["defaults"][field_name] = _as_stored(default)
        return name

    roots = {entity_type: visit(model) for entity_type, model in _roots().items()}
    return {"roots": roots, "models": dict(sorted(models.items()))}


def render(spec: dict[str, Any]) -> str:
    body = pprint.pformat(spec, indent=1, width=88, sort_dicts=True)
    return (
        '"""Field defaults of the definition models, for the merge comparison.\n\n'
        "GENERATED by components/document-store/scripts/"
        "generate_definition_defaults.py\n"
        "from the def-store and template-store models — do not edit by hand.\n"
        "test_definition_defaults_contract fails when this falls behind them.\n"
        '"""\n\n'
        "from typing import Any\n\n"
        f"DEFINITION_DEFAULTS: dict[str, Any] = {body}\n"
    )


def main() -> int:
    text = render(build())
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date — regenerate it", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
