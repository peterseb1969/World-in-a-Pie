"""Garage object-storage configuration (the MinIO successor).

Garage (https://garagehq.deuxfleurs.fr/) serves the same S3 surface WIP
uses — put/get/copy/delete/head object, bucket head/create, presigned
GETs — from a multi-arch, actively published image, which MinIO no longer
provides (docker.io stopped resolving, quay.io answers 401 anonymously;
the interim ghcr copy is arm64-only and frozen).

Three Garage behaviors shape this module, all verified live against
v2.1.0:

- **The SigV4 region is enforced.** A request signed for a region other
  than the configured `s3_region` is rejected with "Authorization header
  malformed". document-store's S3 client signs for its default
  `us-east-1`, so the rendered config pins `s3_region = "us-east-1"`.
- **Presigned URLs must be SigV4, and the signed Host is enforced.**
  Garage treats SigV2 query auth as anonymous (403), and a SigV4
  presigned GET fails when the received Host differs from the signed
  one — hence `upstream_host_header: true` on the route, so the edge
  forwards the internal Host the URL was signed against.
- **Credentials are imported, not read from env.** The deployer
  generates the access key id (GK + 12 hex bytes) and secret (32 hex
  bytes) as install secrets and imports them at apply time
  (`garage json-api ImportKey`), so document-store's `from_secret` env
  and Garage's key material come from the same source and every
  re-render is deterministic.

The rendered garage.toml carries the rpc secret and admin token, so the
renderers write it 0600 — same posture as .env.
"""

from __future__ import annotations

from wip_deploy.secrets_backend.base import ResolvedSecrets
from wip_deploy.spec import Deployment
from wip_deploy.spec.activation import is_component_active
from wip_deploy.spec.component import Component

GARAGE_S3_PORT = 3900
GARAGE_RPC_PORT = 3901
GARAGE_ADMIN_PORT = 3903

GARAGE_BUCKET = "wip-attachments"
# Backup and restore archives (document-store's archive store). Without it
# provisioned, every archive stays in container scratch, swept after a day
# and lost with the container — the files key cannot create buckets itself.
GARAGE_BACKUP_BUCKET = "wip-backups"
# Every bucket provisioning creates and grants the files key on. Each name is
# also a literal in document-store's manifest (WIP_FILE_STORAGE_BUCKET,
# WIP_BACKUP_BUCKET); a deployer test keeps the two in step.
GARAGE_BUCKETS = (GARAGE_BUCKET, GARAGE_BACKUP_BUCKET)
GARAGE_KEY_NAME = "wip-files"

SECRET_RPC = "garage-rpc-secret"
SECRET_ADMIN_TOKEN = "garage-admin-token"
SECRET_KEY_ID = "garage-key-id"
SECRET_KEY_SECRET = "garage-key-secret"

# Every secret the garage module needs collected. rpc/key-id/key-secret
# have format constraints (see secrets.py's name-keyed generators):
# Garage requires rpc_secret = 32 hex-encoded bytes, key ids = "GK" +
# 12 hex bytes, key secrets = 32 hex bytes.
GARAGE_SECRET_NAMES = (
    SECRET_RPC,
    SECRET_ADMIN_TOKEN,
    SECRET_KEY_ID,
    SECRET_KEY_SECRET,
)


def garage_component(
    deployment: Deployment, components: list[Component]
) -> Component | None:
    """The garage component when it is active in this deployment, else None."""
    comp = next((c for c in components if c.metadata.name == "garage"), None)
    if comp is None or not is_component_active(comp, deployment):
        return None
    return comp


def render_garage_toml(secrets: ResolvedSecrets) -> str:
    """The garage.toml the container mounts at /etc/garage.toml.

    Single-node layout (replication_factor 1): the deployer provisions
    the layout at apply time. Multi-node Garage is a deliberate later
    step, not a rendering variant of this file.
    """
    rpc_secret = secrets.get(SECRET_RPC)
    admin_token = secrets.get(SECRET_ADMIN_TOKEN)
    return f"""# Generated by wip-deploy — do not edit (re-render instead).
metadata_dir = "/var/lib/garage/meta"
data_dir = "/var/lib/garage/data"
db_engine = "sqlite"

replication_factor = 1

rpc_bind_addr = "[::]:{GARAGE_RPC_PORT}"
rpc_public_addr = "127.0.0.1:{GARAGE_RPC_PORT}"
rpc_secret = "{rpc_secret}"

[s3_api]
# Garage enforces the SigV4 region: a request signed for another region
# is rejected outright. document-store's S3 client signs for its
# default us-east-1, so this value must stay in lockstep with it.
s3_region = "us-east-1"
api_bind_addr = "[::]:{GARAGE_S3_PORT}"
root_domain = ".s3.garage.invalid"

[admin]
api_bind_addr = "[::]:{GARAGE_ADMIN_PORT}"
admin_token = "{admin_token}"
"""
